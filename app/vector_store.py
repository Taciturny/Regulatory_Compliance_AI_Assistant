"""Pinecone-backed semantic retrieval for CivicData's Nigerian legal corpus."""

from __future__ import annotations

import hashlib
import json
import os
import time
from dataclasses import dataclass
from pathlib import Path

from pinecone import Pinecone, ServerlessSpec


EMBED_MODEL = "llama-text-embed-v2"
EMBED_DIMENSIONS = 1024
CHUNK_SIZE = 2_400
CHUNK_OVERLAP = 300
# v2 deliberately isolates the complete Act + GAID + schedules from any older partial index.
NAMESPACE = "nigerian-data-protection-v2"


@dataclass(frozen=True)
class Passage:
    source: str
    reference: str
    text: str
    url: str

    @property
    def label(self) -> str:
        return f"{self.source} · {self.reference}"


class RetrievalError(RuntimeError):
    """A safe, user-presentable vector retrieval error."""


class LegalVectorStore:
    """Pinecone vector store; embeddings are generated by Pinecone Inference."""

    def __init__(self, documents_dir: Path) -> None:
        self.documents_dir = documents_dir
        # The legacy Pinecone index in the project was named "regulatoryai".
        self.index_name = os.getenv("PINECONE_INDEX_NAME", "regulatoryai").strip()
        self._pc: Pinecone | None = None
        self._index = None

    def _client(self) -> Pinecone:
        key = os.getenv("PINECONE_API_KEY", "").strip()
        if not key:
            raise RetrievalError("Add PINECONE_API_KEY and PINECONE_INDEX_NAME to the deployment environment.")
        if self._pc is None:
            self._pc = Pinecone(api_key=key)
        return self._pc

    def _open_index(self, create: bool = False):
        if self._index is not None:
            return self._index
        pc = self._client()
        try:
            names = {item.name for item in pc.list_indexes()}
            if self.index_name not in names:
                if not create:
                    raise RetrievalError(
                        f"Pinecone index '{self.index_name}' was not found. Run `python -m app.index_legal_sources` once."
                    )
                pc.create_index(
                    name=self.index_name,
                    dimension=EMBED_DIMENSIONS,
                    metric="cosine",
                    spec=ServerlessSpec(
                        cloud=os.getenv("PINECONE_CLOUD", "aws"),
                        region=os.getenv("PINECONE_REGION", "us-east-1"),
                    ),
                )
                deadline = time.monotonic() + 90
                while time.monotonic() < deadline:
                    description = pc.describe_index(self.index_name)
                    if description.status.ready:
                        break
                    time.sleep(2)
                else:
                    raise RetrievalError("Pinecone index is still starting. Retry shortly.")
            description = pc.describe_index(self.index_name)
            if int(description.dimension) != EMBED_DIMENSIONS or str(description.metric).lower() != "cosine":
                raise RetrievalError(
                    f"Pinecone index '{self.index_name}' must use dimension {EMBED_DIMENSIONS} and cosine similarity."
                )
            if not description.status.ready:
                raise RetrievalError("Pinecone index is still starting. Retry shortly.")
            self._index = pc.Index(self.index_name)
            return self._index
        except RetrievalError:
            raise
        except Exception as exc:
            raise RetrievalError("Pinecone is temporarily unavailable. Check its API key and index configuration.") from exc

    @property
    def count(self) -> int:
        try:
            stats = self._open_index().describe_index_stats()
            return int(stats.namespaces.get(NAMESPACE, {}).get("vector_count", 0))
        except RetrievalError:
            return 0
        except Exception as exc:
            raise RetrievalError("Pinecone could not report the legal index status.") from exc

    def _embed(self, texts: list[str], input_type: str) -> list[list[float]]:
        # Caller batches to keep requests small and within hosted-model limits.
        try:
            response = self._client().inference.embed(
                model=EMBED_MODEL,
                inputs=texts,
                parameters={"input_type": input_type, "truncate": "END"},
            )
            vectors = [item.values for item in response.data]
            if len(vectors) != len(texts) or any(len(vector) != EMBED_DIMENSIONS for vector in vectors):
                raise RetrievalError("Pinecone returned an incomplete embedding response.")
            return vectors
        except RetrievalError:
            raise
        except Exception as exc:
            raise RetrievalError("Pinecone embedding is temporarily unavailable.") from exc

    @staticmethod
    def _chunks(text: str) -> list[str]:
        chunks: list[str] = []
        start = 0
        while start < len(text):
            end = min(start + CHUNK_SIZE, len(text))
            if end < len(text):
                boundary = max(text.rfind(". ", start + CHUNK_SIZE // 2, end), text.rfind("; ", start + CHUNK_SIZE // 2, end))
                if boundary > start:
                    end = boundary + 1
            chunk = text[start:end].strip()
            if chunk:
                chunks.append(chunk)
            if end == len(text):
                break
            start = max(end - CHUNK_OVERLAP, start + 1)
        return chunks

    def _source_documents(self) -> list[dict[str, str]]:
        documents: list[dict[str, str]] = []
        sources = (
            ("ndpa.json", "Nigeria Data Protection Act 2023", "Section", "https://ndpc.gov.ng/wp-content/uploads/2024/03/Nigeria_Data_Protection_Act_2023.pdf"),
            ("gaid.json", "NDP Act GAID 2025", "Article", "https://ndpc.gov.ng/wp-content/uploads/2025/07/NDP-ACT-GAID-2025-MARCH-20TH.pdf"),
            ("gaid_schedules.json", "NDP Act GAID 2025", "Schedule", "https://ndpc.gov.ng/wp-content/uploads/2025/07/NDP-ACT-GAID-2025-MARCH-20TH.pdf"),
            ("ndpc_dpo_pathway.json", "NDPC DPO Training and Certification Programme", "Program", "https://forms.ndpc.gov.ng/dpotraining/"),
        )
        for filename, source, provision_type, url in sources:
            records = json.loads((self.documents_dir / filename).read_text(encoding="utf-8"))
            for record in records:
                title = str(record.get(provision_type, "Legal text")).strip()
                number = record.get("Id", "")
                reference = f"{provision_type} {number}: {title}" if number else title
                parts = self._chunks(str(record.get("Content", "")).strip())
                for chunk_number, part in enumerate(parts):
                    identifier = hashlib.sha256(f"{source}\0{reference}\0{part}".encode()).hexdigest()
                    documents.append({"id": identifier, "source": source, "title": reference, "content": part, "url": url,
                                      "chunk_index": str(chunk_number), "provision_chunk_count": str(len(parts))})
        return documents

    def reset_index(self) -> None:
        """Delete and recreate the configured index at the current embedding dimension."""
        pc = self._client()
        try:
            if self.index_name in {item.name for item in pc.list_indexes()}:
                pc.delete_index(self.index_name)
                deadline = time.monotonic() + 90
                while time.monotonic() < deadline:
                    if self.index_name not in {item.name for item in pc.list_indexes()}:
                        break
                    time.sleep(2)
                else:
                    raise RetrievalError("Pinecone index deletion did not complete within 90 seconds.")
            self._index = None
            self._open_index(create=True)
        except RetrievalError:
            raise
        except Exception as exc:
            raise RetrievalError("Could not reset the configured Pinecone index.") from exc

    def build(self, force: bool = False) -> int:
        index = self._open_index(create=True)
        from app.legal_corpus import validate_legal_corpus

        validate_legal_corpus(self.documents_dir)
        documents = self._source_documents()
        try:
            existing = int(index.describe_index_stats().namespaces.get(NAMESPACE, {}).get("vector_count", 0))
            if existing == len(documents) and existing and not force:
                return existing
            prepared: list[dict] = []
            for start in range(0, len(documents), 48):
                batch = documents[start : start + 48]
                embeddings = self._embed([f"{item['title']}\n{item['content']}" for item in batch], "passage")
                prepared.extend(
                    {"id": item["id"], "values": vector,
                     "metadata": {k: item[k] for k in ("source", "title", "content", "url", "chunk_index", "provision_chunk_count")}}
                    for item, vector in zip(batch, embeddings)
                )
            # Only replace the existing corpus after every source has embedded successfully.
            if existing:
                index.delete(delete_all=True, namespace=NAMESPACE)
            for start in range(0, len(prepared), 100):
                index.upsert(vectors=prepared[start : start + 100], namespace=NAMESPACE)
            return len(documents)
        except RetrievalError:
            raise
        except Exception as exc:
            raise RetrievalError("Pinecone could not write the legal index.") from exc

    def search(self, query: str, limit: int = 8) -> list[Passage]:
        index = self._open_index()
        if self.count == 0:
            raise RetrievalError("The legal vector index is empty. Run `python -m app.index_legal_sources` first.")
        query_vector = self._embed([query[:8_000]], "query")[0]
        try:
            result = index.query(vector=query_vector, top_k=max(limit * 4, limit), include_metadata=True, namespace=NAMESPACE)
        except Exception as exc:
            raise RetrievalError("Pinecone search is temporarily unavailable.") from exc
        ranked: dict[str, tuple[dict, float]] = {}
        for match in result.matches:
            ranked[str(match.id)] = (dict(match.metadata or {}), float(match.score or 0))

        groups: dict[tuple[str, str], list[tuple[int, dict, float]]] = {}
        for metadata, score in ranked.values():
            source = str(metadata.get("source", ""))
            reference = str(metadata.get("title", ""))
            if not source or not reference or (score < 0.24 and score < 1.0):
                continue
            key = (source, reference)
            groups.setdefault(key, []).append((int(metadata.get("chunk_index", 0)), metadata, score))
        ordered_groups = sorted(groups.items(), key=lambda item: max(row[2] for row in item[1]), reverse=True)
        passages: list[Passage] = []
        for (source, reference), chunks in ordered_groups:
            chunks.sort(key=lambda row: row[0])
            # Preserve adjacent chunks within a provision; later chunks can contain a qualification or exception.
            # A pair of adjacent chunks retains relevant qualifications while limiting
            # the context sent to the LLM, especially when reviewing pasted contracts.
            text = "\n".join(str(row[1].get("content", "")) for row in chunks[:2])
            url = str(chunks[0][1].get("url", ""))
            passages.append(Passage(source, reference, text, url))
            if len(passages) >= limit:
                break
        return passages
